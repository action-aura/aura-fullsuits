"""Aura Owner as an installable web app (PWA) -- Step 1 of the Aura Growth Plan.

Three public routes, none behind login, none touching the database:

  /manifest.webmanifest?lang=xx  the web app manifest (name, icons, colours)
  /sw.js                         the service worker
  /offline                       the page shown when a navigation fails offline

THE SAFETY POLICY (the reason this file exists in the shape it does).
Every Owner page is behind a login and carries live money / customer /
licence data, and every JSON route is the same. A service worker that cached
any of it would (a) show stale figures as if they were live, and (b) keep a
copy on the phone after logout, where the next person to open the app could
read it offline. So the worker caches exactly one closed list, decided HERE,
on the server, and nowhere else:

  * the files under app/static/ (public CSS/JS/images -- served to anyone,
    logged in or not), and
  * the offline page below, which is rendered WITHOUT the request context
    processors (so no staff name, no counts, no CSRF token can reach it) and
    is fetched by the worker with credentials "omit" (no cookie at all).

Nothing else is ever written to the cache: the worker has no runtime caching
-- the only cache write is the install step over this list. Navigations go
to the network every time; only when the network fails does the offline page
appear. Every other request (API/JSON, downloads, POSTs, cross-origin) is not
intercepted at all. tests/test_pwa.py drives the real rendered worker through
every route the app registers, online and offline, and fails if anything
outside this list ends up cached.

WHY THE WORKER IS SERVED FROM "/" AND NOT /static/. A service worker can only
control pages under the folder it is served from, unless the server adds a
`Service-Worker-Allowed` header. Served from /sw.js its natural scope is the
whole site, so no extra header (and no reverse-proxy rule that could drop
it) is needed.

WHY THE CACHE VERSION IS A HASH. The cache name ends in a sha256 over every
cached file's bytes plus the offline page. Change any static file, deploy,
and the worker's own text changes, so the browser installs the new worker,
which fetches fresh copies and deletes the old cache on activate. Nobody has
to remember to bump a version number on deploy.

WHY THE MANIFEST HAS ?lang=. Browsers fetch the manifest without cookies, so
the server cannot see the user's language from the session; base.html puts
the current language in the URL instead. Both languages share `"id": "/"`, so
switching language never looks like a second app.

ICONS (static/img/brand/icon-192.png, icon-512.png, icon-maskable-512.png,
apple-touch-icon.png) are generated by owner/tools/pwa_icons/make_icons.js
from the flat Owner mark geometry (static/img/brand/action-aura-mark.svg):
ivory A + Owner light-gold ring on the brand dark ground #0E1729, the
brand guide's "flat master on dark" treatment. The repo has no 3D Owner
artwork (aura-owner-dark.svg was never checked in), so the flat mark is used
at every size -- same choice the live website's icon set made.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

from flask import Blueprint, current_app, make_response, request, url_for
from flask_babel import force_locale
from flask_babel import gettext as _

from app.i18n import current_direction, is_supported_locale

bp = Blueprint("pwa", __name__)

#: Cache-name prefix. activate() deletes every OTHER cache with this prefix,
#: and nothing else -- so a future cache (e.g. push assets) must use its own.
CACHE_PREFIX = "aura-owner-static-"

#: Only these file types under app/static/ are precached. All are public
#: assets served without login; nothing under static/ is ever user data.
_PRECACHE_SUFFIXES = (".css", ".js", ".svg", ".png", ".ico", ".woff2")

#: A file larger than this is left to the network rather than bloating the
#: install (none exists today; the whole set is ~0.3 MB).
_PRECACHE_MAX_BYTES = 512 * 1024

# Owner's own CSS tokens (static/css/tokens.css): the top bar is
# --aura-color-surface-raised (#FFFFFF light / #1B1F29 dark) and the page is
# --aura-color-surface-base (#F6F8FA light). The manifest takes the light
# values; base.html's theme-color <meta> pair follows the phone's dark mode.
THEME_COLOR = "#FFFFFF"
BACKGROUND_COLOR = "#F6F8FA"


def _static_precache_files() -> list[tuple[str, Path]]:
    """(url, file) for every precacheable file under app/static/, sorted so
    the version hash is stable across processes."""
    root = Path(current_app.static_folder)
    files = []
    for path in sorted(root.rglob("*")):
        if not path.is_file() or path.suffix.lower() not in _PRECACHE_SUFFIXES:
            continue
        if path.stat().st_size > _PRECACHE_MAX_BYTES:
            continue
        files.append((url_for("static", filename=path.relative_to(root).as_posix()), path))
    return files


def _offline_copy() -> dict[str, dict[str, str]]:
    """Both languages at once: the worker caches ONE offline page for the
    whole install, and the phone may be switched between English and Arabic
    after it was cached."""
    copy = {}
    for code in ("ar", "en"):
        with force_locale(code):
            copy[code] = {
                "title": _("You are offline"),
                "body": _("Aura Owner needs the internet to show live information. Check your connection, then try again."),
                "retry": _("Try again"),
                "dir": current_direction(code),
            }
    return copy


def render_offline_page() -> str:
    # get_template().render(), NOT render_template(): render_template runs the
    # app's context processors, which load the signed-in staff member and
    # their attention counts. This page is cached on the phone and shown to
    # whoever holds it, so it must be impossible -- not merely unlikely -- for
    # anything about a user to reach it.
    template = current_app.jinja_env.get_template("pwa/offline.html")
    return template.render(
        copy=_offline_copy(),
        retry_url=url_for("dashboard.index"),
        mark_url=url_for("static", filename="img/brand/action-aura-mark.svg"),
    )


def build_sw_config() -> dict:
    """The service worker's whole cache policy, as data. Also read directly by
    tests/test_pwa.py's allow-list guard."""
    offline_url = url_for("pwa.offline")
    digest = hashlib.sha256()
    precache = []
    for url, path in _static_precache_files():
        precache.append(url)
        digest.update(url.encode("utf-8") + b"\0" + path.read_bytes() + b"\0")
    digest.update(offline_url.encode("utf-8") + b"\0" + render_offline_page().encode("utf-8"))
    precache.append(offline_url)
    return {
        "version": digest.hexdigest()[:16],
        "cachePrefix": CACHE_PREFIX,
        "precache": precache,
        "offlineUrl": offline_url,
    }


@bp.get("/sw.js")
def service_worker():
    body = current_app.jinja_env.get_template("pwa/sw.js").render(pwa_config=build_sw_config())
    response = make_response(body)
    response.headers["Content-Type"] = "text/javascript; charset=utf-8"
    # The browser re-checks the worker on every navigation; "no-cache" makes
    # that a real revalidation, so a deploy reaches phones on their next page
    # load instead of up to 24 hours later.
    response.headers["Cache-Control"] = "no-cache"
    return response


@bp.get("/offline")
def offline():
    response = make_response(render_offline_page())
    response.headers["Cache-Control"] = "no-cache"
    return response


@bp.get("/manifest.webmanifest")
def manifest():
    requested = request.args.get("lang")
    locale = requested if is_supported_locale(requested) else current_app.config["BABEL_DEFAULT_LOCALE"]
    icons_dir = "img/brand/"
    with force_locale(locale):
        data = {
            "id": "/",
            "name": _("Aura Owner Control Center"),
            # "Aura Owner" is the brand and stays Latin in Arabic too
            # (translation-style-guide.md; the Arabic catalog maps it to
            # itself), so the home-screen label is the same in both.
            "short_name": _("Aura Owner"),
            "description": _("The Action Aura staff console: sales, customers and licences."),
            "lang": locale,
            "dir": current_direction(locale),
            "start_url": url_for("dashboard.index"),
            "scope": "/",
            "display": "standalone",
            "theme_color": THEME_COLOR,
            "background_color": BACKGROUND_COLOR,
            "icons": [
                {"src": url_for("static", filename=icons_dir + "icon-192.png"), "sizes": "192x192",
                 "type": "image/png", "purpose": "any"},
                {"src": url_for("static", filename=icons_dir + "icon-512.png"), "sizes": "512x512",
                 "type": "image/png", "purpose": "any"},
                {"src": url_for("static", filename=icons_dir + "icon-maskable-512.png"), "sizes": "512x512",
                 "type": "image/png", "purpose": "maskable"},
            ],
        }
    response = current_app.response_class(
        json.dumps(data, ensure_ascii=False), mimetype="application/manifest+json"
    )
    response.headers["Cache-Control"] = "no-cache"
    return response
