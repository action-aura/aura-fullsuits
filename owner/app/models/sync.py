import uuid
from datetime import datetime

from sqlalchemy import DateTime, ForeignKey, String, BigInteger, Identity, Index, Integer, Text, text
from sqlalchemy.dialects.postgresql import UUID, JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.extensions import Base
from app.models.base import TimestampMixin, UUIDPKMixin


class SyncEvent(Base, TimestampMixin):
    """Append-only log of business-data mutations shared across every
    device activated against the same license. `seq` (not `created_at`,
    which is client-supplied and untrusted for ordering) is the sole
    ordering authority every client cursors against."""

    __tablename__ = "owner_sync_events"

    # Client-generated (not server default) -- this IS the idempotency key
    # for POST /api/sync/v1/push: a retried push with the same id must be
    # a no-op, never a second row with a new seq.
    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True)
    # BigInteger IDENTITY (not autoincrement=True, which SQLAlchemy only
    # honors on the primary-key column -- id is the PK here, not seq).
    # This compiles to a real Postgres server-side sequence
    # (GENERATED BY DEFAULT AS IDENTITY), the sole ordering authority
    # every client cursors against.
    seq: Mapped[int] = mapped_column(BigInteger, Identity(), unique=True, nullable=False)
    license_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("owner_licenses.id"), nullable=False)
    device_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False)
    entity_type: Mapped[str] = mapped_column(String(64), nullable=False)
    entity_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False)
    event_type: Mapped[str] = mapped_column(String(16), nullable=False)  # create|update|delete
    payload: Mapped[dict] = mapped_column(JSONB, nullable=False)
    client_created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)

    __table_args__ = (
        Index("ix_owner_sync_events_license_seq", "license_id", "seq"),
        # AUDIT-033 / V3o G3: registry_pin's history guard looks up the first
        # event naming a registry device id. Migration 7c41d2e9a0b5.
        Index("ix_owner_sync_events_license_entity", "license_id", "entity_type", "entity_id"),
    )


class SyncDeviceCursor(Base, TimestampMixin):
    """Phase 5 prerequisite #2 (docs/launch-readiness/phase5-prerequisites.md
    section 2) -- the server-side, durable record of how far EACH device has
    caught up, keyed by pull()'s own `since`/returned-`cursor` value. This is
    the one input pruning needs that nothing in the protocol persisted
    before: `since` was purely a stateless request parameter the CLIENT
    tracked locally and resent on its next pull -- the server never wrote
    down "device X has acknowledged everything up to seq N" anywhere. To
    prune below "the slowest device that still needs it", the server needs
    exactly that fact, durably, for a device whose next pull could be days
    away.

    ONLY pull() writes this row (see routes.py::_advance_device_cursor) --
    NEVER push(). A device that only ever pushes (never pulls) would
    otherwise never get a cursor at all, even though it has, by definition,
    already seen (by authoring) every event up to its own latest push's
    seq -- pull()'s own WHERE clause excludes a device's own events
    (`SyncEvent.device_id != installation.id`), so it can never receive them
    back to "acknowledge" them that way. This is handled correctly without
    any push-side special case: a push-only device still gets a cursor
    recorded the next time it calls pull() with `since` set to the current
    max seq, even when that pull returns zero NEW rows (nothing else to
    receive) -- see test_sync_pruning.py's `_push_then_fully_catch_up_both_devices`
    helper for the concrete mechanics this depends on, and the class-level
    consequence: a device that only ever pushes and never pulls keeps
    `last_acked_seq` at its (missing-row) default of "not caught up yet",
    which correctly blocks pruning of its own unacknowledged history rather
    than silently treating "never pulled" as "nothing to lose".

    SYNC-BOOT Phase 1: the PK is (installation_id, stream), not installation_id
    alone. One installation id is shared by TWO client streams -- retail and
    registry -- yet each stream keeps its OWN cursor locally. With one Owner
    row per installation the row followed whichever stream pulled last/fastest,
    so the prune watermark could pass events the lagging stream never applied
    (read in the code, then reproduced by the cross-stack registry-stall test).
    `stream` is 'retail' | 'registry' | 'all' (the LAN hub's forwarder, which
    forwards both) | 'legacy' (an old client that sends no stream; every row that
    existed before this revision was backfilled to it). See pruning.py for how
    the per-stream positions collapse into ONE number per installation.

    `last_pulled_at` is liveness (written at most hourly -- a write per pull
    would be a write per 10 seconds per device); `caps` is the capability list
    the client declared in its signed pull body (None = never declared). Neither
    is read by anything in Phase 1 except tests; Phase 3/4 consume them.

    `license_id` is denormalized onto this row (rather than derived via a
    join back through owner_installations at prune time) purely so
    pruning's per-license MIN(last_acked_seq) query is a single indexed
    lookup, not a join for every prune run."""

    __tablename__ = "owner_sync_device_cursors"

    installation_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("owner_installations.id"), primary_key=True
    )
    stream: Mapped[str] = mapped_column(String(16), primary_key=True, default="legacy", server_default="legacy")
    license_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("owner_licenses.id"), nullable=False)
    # GREATEST-style: routes.py::_advance_device_cursor never lets this
    # regress below its current value, regardless of what a given pull
    # response computed -- see that function's own docstring.
    last_acked_seq: Mapped[int] = mapped_column(BigInteger, nullable=False)
    last_pulled_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    caps: Mapped[list | None] = mapped_column(JSONB)

    __table_args__ = (
        # pruning.py's per-license watermark query filters on license_id
        # for every prune run (once per license, per run) -- this is that
        # query's index, the same shape as owner_sync_events' own
        # license_id-leading index above.
        Index("ix_owner_sync_device_cursors_license", "license_id"),
    )


class SyncLicenseState(Base, TimestampMixin):
    """SYNC-BOOT Phase 1: the one fact the relay never recorded -- how far
    this licence's event log has been PRUNED. Before this row existed a device
    whose cursor sat below the pruned range got a partial, gap-free-looking
    stream back (the missing events simply were not there to return) and no
    error, ever. `pruned_through_seq` is the highest seq ever deleted for the
    licence; pull() answers 409 RESYNC_REQUIRED when `since` is below it.

    Monotonic by construction (pruning.py writes max(old, new) in the same
    transaction as each delete batch). It is ONLY ever written by pruning and
    by the operator's `flask sync mark-pruned`, never by a request and never
    by a migration backfill (seq is shared by all licences, so a first-event
    seq says nothing about whether anything was deleted)."""

    __tablename__ = "owner_sync_license_state"

    license_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("owner_licenses.id"), primary_key=True
    )
    pruned_through_seq: Mapped[int] = mapped_column(BigInteger, nullable=False, default=0, server_default="0")
    last_prune_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class SyncQuarantineEvent(Base, UUIDPKMixin, TimestampMixin):
    """Phase 5 prerequisite #3 (docs/launch-readiness/phase5-prerequisites.md
    section 3) -- one row per push-batch event that failed validation (or
    was rejected by the database itself, e.g. a NUL byte Postgres refuses to
    store) and was therefore SKIPPED rather than rolling back the entire
    batch (see routes.py::_store_events's docstring for the full mechanism
    and the "Never in the request path" / "skip trades strict consistency
    for availability" reasoning, which belongs there since that's where the
    trade is actually made).

    `raw_payload` is the event exactly as the device sent it -- byte-
    identical, never partially parsed or normalized -- so a fixed/replayed
    submission (see quarantine_routes.py::replay) reproduces precisely what
    the device originally pushed, and an operator reading the console can
    see exactly what the client actually sent. `batch_index` is this
    event's position within ITS OWN push batch (0-based), not a global
    counter -- lets an operator correlate a quarantined row back to "the
    3rd item in that particular push" if they're comparing against client-
    side logs.

    `status` starts PENDING and moves to REPLAYED (successfully re-applied
    as a real SyncEvent once the underlying cause was fixed) or DISCARDED
    (an operator decided it's not worth fixing) -- never DELETEd. "Nothing
    is ever silently dropped": every quarantined event stays visible and
    queryable in the Owner console regardless of its resolution, forever."""

    __tablename__ = "owner_sync_quarantine"

    license_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("owner_licenses.id"), nullable=False)
    device_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False)
    batch_index: Mapped[int] = mapped_column(Integer, nullable=False)
    raw_payload: Mapped[dict] = mapped_column(JSONB, nullable=False)
    # Text, not a bounded String: a DataError's message (the DB-rejection
    # path, as opposed to _build_event's own short InvalidEventError
    # strings) is driver-formatted prose of unpredictable length -- better
    # to keep it whole than silently truncate the one clue an operator has
    # for why the row was rejected.
    rejection_reason: Mapped[str] = mapped_column(Text, nullable=False)
    status: Mapped[str] = mapped_column(String(16), default="PENDING", nullable=False)  # PENDING|REPLAYED|DISCARDED
    resolved_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    resolved_by_staff_user_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("owner_staff_users.id")
    )

    __table_args__ = (
        # pruning.py's quarantine-rate alarm groups PENDING rows by
        # license_id on every run; the console's default list view filters
        # by status too -- this composite index covers both access patterns.
        Index("ix_owner_sync_quarantine_license_status", "license_id", "status"),
    )


#: Statuses in which a bootstrap request still blocks a second one for the same
#: (requester, stream) -- the partial unique index below is built from this list.
BOOTSTRAP_OPEN_STATUSES = ("OPEN", "CLAIMED", "READY", "DELIVERED")


class SyncBootstrapRequest(Base, UUIDPKMixin, TimestampMixin):
    """SYNC-BOOT Phase 3: one row per "a device needs a fresh copy of the shop".

    A device whose pull is refused with RESYNC_REQUIRED cannot be replayed the
    history Owner already pruned, so it asks a peer that HOLDS the shop's data for
    a consistent copy and Owner is only the mailbox between them: the producer
    uploads an ENCRYPTED copy in chunks, the requester downloads it and acks, and
    the bytes are deleted. The row carries the lifecycle:

        OPEN       waiting for a producer
        CLAIMED    one producer holds a 30-minute lease (first claim wins)
        READY      every chunk uploaded and counted; the requester may download
        DELIVERED  the requester acked and the bytes are gone (data half done)
        FULFILLED  the data half AND the authority half are done. The authority
                   half is the MAIN computer re-announcing users, permissions and
                   numbering books, signed -- authority is never copied. A
                   registry-stream request has no data half: OPEN -> FULFILLED.
        EXPIRED    nobody finished within `expires_at` (72 h); blob removed
        FAILED     superseded by a newer request from the same device, or refused

    OPEN, CLAIMED, READY and DELIVERED count as "open": at most one such row per
    (requester installation, stream) -- a device retrying every ten seconds is
    one request, not a pile. `enc_pubkey` is the requester's single-use X25519
    public key; Owner never sees a private key, so it cannot read the copy it
    carries. The encrypted bytes live on a filesystem directory
    (OWNER_SYNC_BOOTSTRAP_DIR, never Neon, never in backups); `blob_ref` names
    this request's subdirectory. `manifest` holds the PUBLIC transport facts the
    requester needs to decrypt (ephemeral key, salt, chunk count, sizes) plus
    whether the authority half has been fulfilled -- not secrets."""

    __tablename__ = "owner_sync_bootstrap_requests"

    license_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("owner_licenses.id"), nullable=False)
    requester_installation_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("owner_installations.id"), nullable=False
    )
    stream: Mapped[str] = mapped_column(String(16), nullable=False)          # retail | registry
    reason: Mapped[str] = mapped_column(String(32), nullable=False, default="join")
    status: Mapped[str] = mapped_column(String(16), nullable=False, default="OPEN")
    # The highest seq of the requester's OWN events: the copy must contain them,
    # because Owner never sends a device its own events back.
    min_as_of: Mapped[int] = mapped_column(BigInteger, nullable=False, default=0, server_default="0")
    # Registry requests: where the registry stream resumes (the licence's top seq
    # when asked); the main computer's fresh re-announce lands after it.
    fast_forward_to: Mapped[int | None] = mapped_column(BigInteger)
    requester_schema_version: Mapped[int | None] = mapped_column(Integer)
    requester_app_version: Mapped[str | None] = mapped_column(String(64))
    enc_pubkey: Mapped[str] = mapped_column(String(64), nullable=False)
    producer_installation_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("owner_installations.id")
    )
    claim_expires_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    manifest: Mapped[dict | None] = mapped_column(JSONB)
    blob_ref: Mapped[str | None] = mapped_column(String(128))
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)

    __table_args__ = (
        Index(
            "uq_owner_sync_bootstrap_open_per_requester_stream",
            "requester_installation_id", "stream",
            unique=True,
            postgresql_where=text("status IN ('OPEN','CLAIMED','READY','DELIVERED')"),
        ),
        Index("ix_owner_sync_bootstrap_license_status", "license_id", "status"),
    )
