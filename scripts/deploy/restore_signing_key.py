"""Register an EXISTING Owner signing-key PEM in a fresh database, then
activate it -- the missing step between "copy the PEM onto the new server"
and "flask licensing activate-signing-key <id>" that this repo's CLI does
not otherwise provide.

## Why this script exists

`flask licensing activate-signing-key <key_id>` (owner/app/cli.py) requires
a matching `owner_signing_keys` DB row to already exist -- see
`activate_signing_key()` in owner/app/licensing_service/signing.py:
"if row is None: raise SigningKeyError(f'No such signing key: {key_id}')".
A brand-new Postgres database (Neon, or any fresh Owner deploy) has NO such
row for a key that was generated by a previous, now-gone deployment -- only
the PEM file itself, once you've copied it over. Following the runbook's
"copy the PEM in, then activate it" instruction literally, with only the
existing CLI, fails at the activate step with "No such signing key", and
the ONLY other command available (`flask licensing generate-signing-key`)
mints a brand-new, different key -- which is exactly the outcome the whole
signing-key section of docs/ops/free-hosting-owner.md exists to prevent
(every already-built installer trusts ONLY the key_id baked into its
bundled commercial_runtime/licensing_contracts/trust_anchor.json; a new
key_id is invisible to it and every activation fails UNKNOWN_SIGNING_KEY).

This script re-derives the key's public half from the PEM file itself
(never trusts a value typed on the command line), optionally cross-checks
it against a locally available trust_anchor.json, inserts the matching
`owner_signing_keys` row, and then calls the REAL, unmodified
`activate_signing_key()` from owner/app/licensing_service/signing.py to do
the retire-previous/activate-new step -- so the actual activation logic is
never duplicated here, only the missing "register a pre-existing key's
metadata" step is added.

## Usage (run INSIDE the owner container, after copying the PEM in)

    docker compose -f owner/deploy/oracle-free/docker-compose.yml exec owner \\
      python /app/scripts/deploy/restore_signing_key.py owner-ed25519-20260903T160641Z-cdcaa65b

The PEM must already be at
`$OWNER_SIGNING_KEY_DIRECTORY/<key_id>.pem` (exactly where
`docker cp <local-pem> <container>:/app/owner/var/signing-keys/<key_id>.pem`
would put it -- see docs/ops/free-hosting-owner.md section 4.4).

By default this also cross-checks the derived public key against
`/app/trust_anchor.reference.json` and REFUSES to proceed if the key_id is
listed there under a DIFFERENT public key. That file is NOT baked into the
image or bind-mounted automatically (commercial_runtime/licensing_contracts/
trust_anchor.json is gitignored -- permanently, not just "not yet
committed" -- so it will not exist on a fresh `git clone`); copy it onto the
container the same way as the PEM, e.g.
`docker cp trust_anchor.json <container>:/app/trust_anchor.reference.json`,
before running this script. Pass --trust-anchor to point at a different
path, or --skip-trust-anchor-check to bypass the cross-check entirely (never
do this for the key your installers already trust -- only
for a deliberate first-ever key with nothing yet to conflict with).

Idempotent: safe to re-run. If the DB row already exists with the same
public key, it is left alone and simply (re-)activated. If it exists with a
DIFFERENT public key under the same key_id, this refuses loudly rather than
silently overwriting trust metadata -- that state means something has
already gone wrong and needs a human, not a script, to sort out.
"""
from __future__ import annotations

import argparse
import base64
import json
import os
import sys

# The Dockerfile.staging image this runs inside has WORKDIR /app/owner and
# the app package at /app/owner/app -- but `docker compose exec` does not
# guarantee cwd, so make this robust to being invoked from anywhere in the
# container.
sys.path.insert(0, "/app/owner")


def _fail(message: str) -> "NoReturn":  # noqa: F821 -- typing.NoReturn optional import avoided for a 1-file script
    print(f"REFUSING: {message}", file=sys.stderr)
    sys.exit(1)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    parser.add_argument("key_id", help="The existing key's id, e.g. owner-ed25519-20260903T160641Z-cdcaa65b")
    parser.add_argument(
        "--trust-anchor",
        default="/app/trust_anchor.reference.json",
        help="Path to a trust_anchor.json to cross-check the PEM's public key against (default: the read-only "
        "bind mount docker-compose.yml provides for this).",
    )
    parser.add_argument(
        "--skip-trust-anchor-check",
        action="store_true",
        help="Bypass the cross-check. Only for a deliberate first-ever key with nothing to conflict with -- "
        "never for the key your existing installers already trust.",
    )
    args = parser.parse_args()

    from app import create_app  # noqa: E402
    from app.extensions import db_session  # noqa: E402
    from app.licensing_service import signing as signing_service  # noqa: E402
    from app.models.licensing_service import SigningKey  # noqa: E402
    from sqlalchemy import select  # noqa: E402

    app = create_app()
    with app.app_context():
        key_directory = app.config["SIGNING_KEY_DIRECTORY"]

        # Reuses the module's own path-safety check and PEM loader rather
        # than re-implementing path validation here.
        try:
            private_key = signing_service.load_private_key(key_directory, args.key_id)
        except signing_service.SigningKeyError as exc:
            _fail(
                f"{exc} Copy the PEM to "
                f"{os.path.join(key_directory, args.key_id + '.pem')} before running this script."
            )

        from cryptography.hazmat.primitives import serialization
        from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

        assert isinstance(private_key, Ed25519PrivateKey)
        public_bytes = private_key.public_key().public_bytes(
            encoding=serialization.Encoding.Raw, format=serialization.PublicFormat.Raw
        )
        derived_public_key = base64.b64encode(public_bytes).decode("ascii")

        if not args.skip_trust_anchor_check:
            if os.path.exists(args.trust_anchor):
                anchor = json.load(open(args.trust_anchor, encoding="utf-8"))
                anchor_entry = next((k for k in anchor.get("keys", []) if k.get("key_id") == args.key_id), None)
                if anchor_entry is not None and anchor_entry.get("public_key") != derived_public_key:
                    _fail(
                        f"The PEM at {key_directory}/{args.key_id}.pem does NOT match the public key already "
                        f"trusted under this key_id in {args.trust_anchor}. Proceeding would register the wrong "
                        "key material under a trusted id. Do not use --skip-trust-anchor-check to get past this "
                        "-- get the correct PEM instead."
                    )
                elif anchor_entry is not None:
                    print(f"Trust-anchor cross-check OK: {args.key_id} matches the publicly trusted key.")
                else:
                    print(
                        f"NOTE: {args.key_id} is not listed in {args.trust_anchor} at all -- cross-check skipped "
                        "(nothing to compare against)."
                    )
            else:
                print(
                    f"WARNING: trust-anchor file not found at {args.trust_anchor} -- proceeding WITHOUT a "
                    "cross-check. If this is meant to restore the key every existing installer already trusts, "
                    "stop and 'docker cp' trust_anchor.json onto the container at that path first instead of "
                    "proceeding blind."
                )

        existing = db_session.execute(select(SigningKey).where(SigningKey.key_id == args.key_id)).scalars().first()
        if existing is not None:
            if existing.public_key != derived_public_key:
                _fail(
                    f"A signing_keys row for {args.key_id} already exists in this database with a DIFFERENT "
                    "public key than the PEM just loaded. This means the database and the PEM disagree about "
                    "what this key_id is -- a human needs to resolve that, not this script."
                )
            print(f"{args.key_id} is already registered in this database with matching key material.")
        else:
            row = SigningKey(
                key_id=args.key_id, algorithm="ed25519", public_key=derived_public_key, status="DRAFT"
            )
            db_session.add(row)
            db_session.commit()
            print(f"Registered {args.key_id} in the database (status=DRAFT).")

        activated = signing_service.activate_signing_key(key_directory, args.key_id)
        print(f"Activated {activated.key_id}. Run 'flask commercial preflight' next to confirm.")


if __name__ == "__main__":
    main()
